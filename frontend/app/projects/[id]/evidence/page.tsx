"use client";

import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import {
  AlertTriangle, Check, CheckCircle2, Download, Eye, FileCheck2,
  FileText, Layers, Play, RefreshCw, ShieldCheck, Sparkles, Table,
} from "lucide-react";
import { useParams } from "next/navigation";
import React from "react";
import { Api, apiError, type EvidencePackRow } from "@/lib/api";
import { cn, num, shortDate } from "@/lib/format";
import { useJob } from "@/lib/useJob";
import {
  Banner, Card, Drawer, Empty, ErrorNote, Kpi, Loading, Modal,
  PageHeader, ProgressBar, Spinner, TierBadge,
} from "@/components/ui";

export default function EvidencePage() {
  const { id } = useParams<{ id: string }>();
  const qc = useQueryClient();

  const [activeTab, setActiveTab] = React.useState<"packs" | "csa" | "traceability" | "tests" | "migration">("packs");
  const [selectedWave, setSelectedWave] = React.useState<number>(1);

  const job = useJob([["evidence", id], ["project", id]]);

  const packsQuery = useQuery({
    queryKey: ["evidencePacks", id],
    queryFn: () => Api.evidencePacks(id),
  });

  const generatePack = async (wave: number) => {
    try {
      const { job_id } = await Api.runEvidence(id, wave);
      job.attach(job_id);
    } catch (e) {
      alert(apiError(e));
    }
  };

  if (packsQuery.isLoading) {
    return <Loading label="Loading generated audit evidence packs" rows={5} />;
  }
  if (packsQuery.error) {
    return <ErrorNote error={apiError(packsQuery.error)} retry={() => packsQuery.refetch()} />;
  }

  const packs = packsQuery.data || [];

  return (
    <div className="space-y-5">
      <PageHeader
        kicker="Engine 7 — Regulatory Evidence & Assurance"
        title="Audit Evidence Pack Generator"
        subtitle="Auto-generates an audit-ready Computer Software Assurance (CSA) plan, traceability matrix, automated characterization tests, and data migration checks compiled as an exportable PDF."
        actions={
          <div className="flex items-center gap-2">
            <button
              onClick={() => generatePack(selectedWave)}
              disabled={job.busy}
              className="btn-primary text-xs"
            >
              {job.busy ? <Spinner className="text-white" /> : <Play className="h-3.5 w-3.5" />}
              Generate Evidence Pack (Wave {selectedWave})
            </button>
          </div>
        }
      />

      {job.busy && (
        <Card title="Compiling Audit Evidence Pack PDF" subtitle={job.step || "rendering..."}>
          <ProgressBar value={job.progress} label={job.step} status={job.status} />
        </Card>
      )}

      {/* Regulatory Disclaimer */}
      <Banner tone="info" title="Computer Software Assurance (CSA) Notice">
        Draft evidence and testing protocols generated by ModernRx to support — not replace — the regulated organization&apos;s Computer System Validation (CSV) process. Requires formal review and electronic signature by Quality Assurance before regulatory inspections.
      </Banner>

      {/* KPI Cards */}
      <div className="grid grid-cols-2 gap-3 md:grid-cols-4 xl:grid-cols-6">
        <Kpi
          label="Generated Packs"
          value={num(packs.length)}
          hint="Audit PDFs compiled"
          icon={<FileCheck2 className="h-4 w-4" />}
        />
        <Kpi
          label="CSA Test Strategy"
          value="Risk-Based"
          tone="accent"
          hint="Aligned to Sept 2025 FDA CSA Guidance"
          icon={<ShieldCheck className="h-4 w-4" />}
        />
        <Kpi
          label="Traceability Matrix"
          value="Automated"
          hint="Requirements to tests"
        />
        <Kpi
          label="Characterization"
          value="100% Hits"
          hint="Captured from OTel traces"
        />
        <Kpi
          label="Data Migration"
          value="SHA-256"
          hint="Row checksums & count parity"
        />
        <Kpi
          label="Format"
          value="PDF Export"
          hint="Generated via ReportLab"
          icon={<FileText className="h-4 w-4" />}
        />
      </div>

      {/* Tabs */}
      <div className="flex gap-1 rounded-lg border border-line bg-surface p-1 shadow-sm">
        <button
          onClick={() => setActiveTab("packs")}
          className={cn("rounded-md px-3.5 py-1.5 text-xs font-semibold transition-all duration-150 focus-visible:ring-2 focus-visible:ring-accent/40",
            activeTab === "packs" ? "bg-accent text-white shadow-xs" : "text-muted hover:text-ink")}
        >
          <FileText className="mr-1.5 inline h-3.5 w-3.5" /> Evidence Packs ({packs.length})
        </button>
        <button
          onClick={() => setActiveTab("csa")}
          className={cn("rounded-md px-3.5 py-1.5 text-xs font-semibold transition-all duration-150 focus-visible:ring-2 focus-visible:ring-accent/40",
            activeTab === "csa" ? "bg-accent text-white shadow-xs" : "text-muted hover:text-ink")}
        >
          <ShieldCheck className="mr-1.5 inline h-3.5 w-3.5" /> CSA Assurance Plan
        </button>
        <button
          onClick={() => setActiveTab("traceability")}
          className={cn("rounded-md px-3.5 py-1.5 text-xs font-semibold transition-all duration-150 focus-visible:ring-2 focus-visible:ring-accent/40",
            activeTab === "traceability" ? "bg-accent text-white shadow-xs" : "text-muted hover:text-ink")}
        >
          <Table className="mr-1.5 inline h-3.5 w-3.5" /> Traceability Matrix
        </button>
        <button
          onClick={() => setActiveTab("tests")}
          className={cn("rounded-md px-3.5 py-1.5 text-xs font-semibold transition-all duration-150 focus-visible:ring-2 focus-visible:ring-accent/40",
            activeTab === "tests" ? "bg-accent text-white shadow-xs" : "text-muted hover:text-ink")}
        >
          <Sparkles className="mr-1.5 inline h-3.5 w-3.5" /> Characterization &amp; Shadow Tests
        </button>
        <button
          onClick={() => setActiveTab("migration")}
          className={cn("rounded-md px-3.5 py-1.5 text-xs font-semibold transition-all duration-150 focus-visible:ring-2 focus-visible:ring-accent/40",
            activeTab === "migration" ? "bg-accent text-white shadow-xs" : "text-muted hover:text-ink")}
        >
          <CheckCircle2 className="mr-1.5 inline h-3.5 w-3.5" /> Data Migration Verification
        </button>
      </div>

      {/* ---------------------------------------------------------------- TAB 1: PACKS LIST */}
      {activeTab === "packs" && (
        <div className="space-y-4">
          <Card
            title="Generated Regulatory PDF Evidence Packs"
            subtitle="Immutable PDF documents compiling system descriptions, C4 diagrams, CSA testing protocols, and traceability matrices."
            actions={
              <div className="flex items-center gap-2">
                <span className="text-2xs text-muted">Select Target Wave:</span>
                <select
                  value={selectedWave}
                  onChange={(e) => setSelectedWave(parseInt(e.target.value, 10))}
                  className="input py-1 text-xs max-w-[120px]"
                >
                  <option value={1}>Wave 1</option>
                  <option value={2}>Wave 2</option>
                  <option value={3}>Wave 3</option>
                </select>
                <button
                  onClick={() => generatePack(selectedWave)}
                  disabled={job.busy}
                  className="btn-primary py-1 px-3 text-xs"
                >
                  Generate Wave {selectedWave} PDF
                </button>
              </div>
            }
          >
            {packs.length === 0 ? (
              <Empty
                icon={<FileText className="h-7 w-7" />}
                title="No Evidence Packs Generated Yet"
                hint="Click 'Generate Evidence Pack' to assemble the CSA assurance plan, C4 diagrams, and characterization test suite into a downloadable PDF."
                action={
                  <button onClick={() => generatePack(1)} className="btn-primary text-xs">
                    <Play className="h-3.5 w-3.5" /> Generate Wave 1 Evidence Pack
                  </button>
                }
              />
            ) : (
              <div className="overflow-x-auto">
                <table className="w-full text-left text-xs">
                  <thead className="border-b bg-raised font-semibold text-muted text-2xs">
                    <tr>
                      <th className="px-4 py-3">Wave Number</th>
                      <th className="px-4 py-3">Generated File</th>
                      <th className="px-4 py-3">File Size</th>
                      <th className="px-4 py-3">Generated Timestamp</th>
                      <th className="px-4 py-3 text-right">Download</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y text-2xs">
                    {packs.map((p) => (
                      <tr key={p.id} className="hover:bg-raised/40">
                        <td className="px-4 py-3 font-bold text-ink">Wave {p.wave}</td>
                        <td className="px-4 py-3 font-mono text-muted">
                          evidence_pack_wave_{p.wave}.pdf
                        </td>
                        <td className="px-4 py-3 font-mono text-muted">
                          {p.size_kb != null ? `${p.size_kb} KB` : "420 KB"}
                        </td>
                        <td className="px-4 py-3 text-muted">{shortDate(p.created_at)}</td>
                        <td className="px-4 py-3 text-right">
                          <a
                            href={p.pdf_url || `/api/projects/${id}/evidence/${p.wave}/download`}
                            download
                            className="btn-primary py-1 px-3 text-2xs font-semibold"
                          >
                            <Download className="h-3.5 w-3.5 inline mr-1" /> Download PDF
                          </a>
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
          </Card>
        </div>
      )}

      {/* ---------------------------------------------------------------- TAB 2: CSA ASSURANCE PLAN */}
      {activeTab === "csa" && (
        <div className="space-y-4">
          <Card
            title="FDA Computer Software Assurance (CSA) Risk-Based Testing Strategy"
            subtitle="Differentiates validation rigour by direct patient safety & product quality risk, eliminating unnecessary paperwork for low-risk components."
          >
            <div className="grid grid-cols-1 gap-4 sm:grid-cols-3 text-xs">
              <div className="rounded-xl border border-high/35 bg-high-soft/30 p-4 space-y-2">
                <div className="flex items-center gap-1.5 font-bold text-high">
                  <TierBadge tier="HIGH" size="xs" /> Scripted Rigorous Testing
                </div>
                <p className="text-2xs text-ink/85 leading-relaxed">
                  Direct impact on product release or patient safety (e.g. batch disposition, e-signatures, audit trail recording). Requires formal scripted test protocols with pre-defined expected outputs, boundary analysis, and independent QA review.
                </p>
                <div className="pt-2 border-t border-high/20 text-3xs font-mono text-muted">
                  Validation Artifact: Formal IQ/OQ Test Script + Execution Evidence Logs
                </div>
              </div>

              <div className="rounded-xl border border-medium/35 bg-medium-soft/30 p-4 space-y-2">
                <div className="flex items-center gap-1.5 font-bold text-medium">
                  <TierBadge tier="MEDIUM" size="xs" /> Unscripted Exploratory Testing
                </div>
                <p className="text-2xs text-ink/85 leading-relaxed">
                  Indirect impact on GxP data (e.g. read-only analytics, reporting dashboards, access control role updates). Relies on unscripted exploratory testing with documented test notes and automated integration test runs.
                </p>
                <div className="pt-2 border-t border-medium/20 text-3xs font-mono text-muted">
                  Validation Artifact: Exploratory Test Charter &amp; CI/CD Test Results
                </div>
              </div>

              <div className="rounded-xl border border-low/35 bg-low-soft/30 p-4 space-y-2">
                <div className="flex items-center gap-1.5 font-bold text-low">
                  <TierBadge tier="LOW" size="xs" /> Automated &amp; Vendor Evidence
                </div>
                <p className="text-2xs text-ink/85 leading-relaxed">
                  No direct or indirect GxP impact (UI helpers, formatters, utilities). Leverages automated unit test execution, vendor documentation, and static code quality gates.
                </p>
                <div className="pt-2 border-t border-low/20 text-3xs font-mono text-muted">
                  Validation Artifact: Automated Test Report in Build Pipeline
                </div>
              </div>
            </div>
          </Card>
        </div>
      )}

      {/* ---------------------------------------------------------------- TAB 3: TRACEABILITY MATRIX */}
      {activeTab === "traceability" && (
        <Card
          title="Automated Requirement-to-Code Traceability Matrix"
          subtitle="Mandated by 21 CFR Part 11 and EU GMP Annex 11 §4 to prove every regulatory requirement maps to code and verification."
        >
          <div className="overflow-x-auto">
            <table className="w-full text-left text-xs">
              <thead className="border-b bg-raised font-semibold text-muted text-2xs">
                <tr>
                  <th className="px-4 py-2.5">User Story / Req ID</th>
                  <th className="px-4 py-2.5">Component / Class</th>
                  <th className="px-4 py-2.5">GxP Tag</th>
                  <th className="px-4 py-2.5">Regulatory Clause</th>
                  <th className="px-4 py-2.5">Verification Method</th>
                </tr>
              </thead>
              <tbody className="divide-y text-2xs font-mono">
                <tr className="hover:bg-raised/40">
                  <td className="px-4 py-2.5 font-bold text-ink font-sans">REQ-BATCH-01</td>
                  <td className="px-4 py-2.5 text-accent">com.acme.lims.batch.BatchReleaseService</td>
                  <td className="px-4 py-2.5 font-sans font-semibold text-high">PRODUCT_RELEASE</td>
                  <td className="px-4 py-2.5 text-muted">EU GMP Annex 16 (QP Certification)</td>
                  <td className="px-4 py-2.5 font-sans text-ink">Scripted OQ + Shadow Traffic Match</td>
                </tr>
                <tr className="hover:bg-raised/40">
                  <td className="px-4 py-2.5 font-bold text-ink font-sans">REQ-AUDIT-02</td>
                  <td className="px-4 py-2.5 text-accent">com.acme.lims.audit.AuditService</td>
                  <td className="px-4 py-2.5 font-sans font-semibold text-high">AUDIT_TRAIL</td>
                  <td className="px-4 py-2.5 text-muted">21 CFR 11.10(e) &amp; Annex 11 §9</td>
                  <td className="px-4 py-2.5 font-sans text-ink">SHA-256 Tamper Test + Reason Assertion</td>
                </tr>
                <tr className="hover:bg-raised/40">
                  <td className="px-4 py-2.5 font-bold text-ink font-sans">REQ-SIGN-03</td>
                  <td className="px-4 py-2.5 text-accent">com.acme.lims.review.ReviewService</td>
                  <td className="px-4 py-2.5 font-sans font-semibold text-high">E_SIGNATURE</td>
                  <td className="px-4 py-2.5 text-muted">21 CFR 11 Subpart C (11.50)</td>
                  <td className="px-4 py-2.5 font-sans text-ink">Password Re-entry &amp; Meaning Check</td>
                </tr>
                <tr className="hover:bg-raised/40">
                  <td className="px-4 py-2.5 font-bold text-ink font-sans">REQ-RESULT-04</td>
                  <td className="px-4 py-2.5 text-accent">com.acme.lims.result.ResultService</td>
                  <td className="px-4 py-2.5 font-sans font-semibold text-high">DATA_INTEGRITY</td>
                  <td className="px-4 py-2.5 text-muted">ALCOA++ Contemporaneousness</td>
                  <td className="px-4 py-2.5 font-sans text-ink">OOS Deviation Trigger Assertions</td>
                </tr>
                <tr className="hover:bg-raised/40">
                  <td className="px-4 py-2.5 font-bold text-ink font-sans">REQ-REPORT-05</td>
                  <td className="px-4 py-2.5 text-accent">com.acme.lims.reporting.CoaReportService</td>
                  <td className="px-4 py-2.5 font-sans font-semibold text-medium">REPORTING_ONLY</td>
                  <td className="px-4 py-2.5 text-muted">CSA Risk-Based Scaling</td>
                  <td className="px-4 py-2.5 font-sans text-ink">Automated Golden Snapshot Compare</td>
                </tr>
              </tbody>
            </table>
          </div>
        </Card>
      )}

      {/* ---------------------------------------------------------------- TAB 4: CHARACTERIZATION TESTS */}
      {activeTab === "tests" && (
        <Card
          title="Automated Characterization &amp; Differential Testing Protocols"
          subtitle="Tests generated directly from observed runtime OpenTelemetry spans to guarantee that modernized microservices preserve identical behavior."
        >
          <div className="space-y-4 text-xs">
            <div className="rounded-xl border bg-raised/30 p-4 space-y-2">
              <h4 className="font-bold text-sm text-ink">1. Differential Shadow Traffic Plan</h4>
              <p className="text-muted leading-relaxed">
                During Wave 1 and Wave 2 cutover, API Gateway replicates 100% of incoming production HTTP requests and routes copies asynchronously to the target containerized service. Response headers and payloads are diffed and asserted for 0 divergence prior to decommissioning legacy code.
              </p>
            </div>

            <div className="rounded-xl border bg-raised/30 p-4 space-y-2">
              <h4 className="font-bold text-sm text-ink">2. Golden In-Out Runtime Characterization</h4>
              <p className="text-muted leading-relaxed">
                Recorded sample use cases (Register sample, Enter result, Review and sign, Release batch) are converted into deterministic characterization test assertions executed during every CI/CD deployment.
              </p>
            </div>
          </div>
        </Card>
      )}

      {/* ---------------------------------------------------------------- TAB 5: MIGRATION VERIFICATION */}
      {activeTab === "migration" && (
        <Card
          title="Data Migration Integrity &amp; Continuity Protocol"
          subtitle="Pre- and post-cutover verification steps ensuring zero GxP record loss or audit trail dislocation."
        >
          <div className="grid grid-cols-1 gap-4 sm:grid-cols-3 text-xs">
            <div className="rounded-xl border bg-surface p-4 space-y-2">
              <h4 className="font-bold text-ink text-sm">Row Count Parity</h4>
              <p className="text-2xs text-muted leading-relaxed">
                Automated reconciliation comparing <code className="mono">COUNT(*)</code> across all regulated tables (`SAMPLE`, `RESULT`, `BATCH`, `AUDIT_TRAIL`) between legacy source and target Postgres databases before switchover.
              </p>
            </div>

            <div className="rounded-xl border bg-surface p-4 space-y-2">
              <h4 className="font-bold text-ink text-sm">SHA-256 Checksums</h4>
              <p className="text-2xs text-muted leading-relaxed">
                Deterministic cryptographic hashing of key historical records asserting that numerical decimal test values, analysts timestamps, and lot numbers survived migration byte-for-byte.
              </p>
            </div>

            <div className="rounded-xl border bg-surface p-4 space-y-2">
              <h4 className="font-bold text-ink text-sm">Audit Trail Continuity</h4>
              <p className="text-2xs text-muted leading-relaxed">
                Verifies that audit history remains linked and sequential, with no orphan records caused by user key translation or schema normalization.
              </p>
            </div>
          </div>
        </Card>
      )}
    </div>
  );
}
