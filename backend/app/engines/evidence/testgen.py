"""Engine 7, part 2 — characterisation test generation (PRD §14.4).

Characterisation tests record what the system does *now*, so that after the
migration you can demonstrate it still does the same thing. They are not
correctness tests: if the legacy behaviour is odd, the test encodes the odd
behaviour, because preserving behaviour is the whole point.

Tests are generated from the twin: the runtime traces say which methods are
actually exercised and how often, and the graph says what each one reads and
writes. Generated as runnable JUnit 5 source plus an HTTP-level suite.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any

from ...db.graph import KnowledgeGraph


@dataclass
class GeneratedTest:
    name: str
    target: str
    node_id: str
    kind: str                     # unit | integration | http | data
    tier: str
    language: str
    source: str
    rationale: str
    runtime_hits: int = 0

    def as_dict(self) -> dict[str, Any]:
        return self.__dict__.copy()


@dataclass
class TestSuite:
    tests: list[GeneratedTest] = field(default_factory=list)
    coverage_note: str = ""
    stats: dict[str, Any] = field(default_factory=dict)

    def as_dict(self) -> dict[str, Any]:
        return {
            "tests": [t.as_dict() for t in self.tests],
            "coverage_note": self.coverage_note,
            "stats": self.stats,
        }


def _java_ident(name: str) -> str:
    out = re.sub(r"[^A-Za-z0-9]", "_", name)
    return out[:1].upper() + out[1:] if out else "Case"


def _sample_value(java_type: str, index: int = 0) -> str:
    """A plausible literal for a parameter type, for a skeleton to compile."""
    t = (java_type or "").split("<")[0].replace("[]", "").strip().rsplit(".", 1)[-1]
    return {
        "long": f"{1000 + index}L", "Long": f"{1000 + index}L",
        "int": str(10 + index), "Integer": str(10 + index),
        "double": f"{1.0 + index}", "Double": f"{1.0 + index}",
        "float": f"{1.0 + index}f", "boolean": "true", "Boolean": "true",
        "String": f'"VALUE_{index}"',
        "BigDecimal": f'new BigDecimal("{10 + index}.5")',
        "Date": "new Date()", "Timestamp": "new Timestamp(System.currentTimeMillis())",
        "LocalDate": "LocalDate.now()", "LocalDateTime": "LocalDateTime.now()",
    }.get(t, "null")


def generate_for_class(kg: KnowledgeGraph, cid: str, *, max_methods: int = 6) -> GeneratedTest | None:
    """One JUnit 5 characterisation test class per analysed class."""
    node = kg.node(cid)
    if node is None:
        return None
    fqn = str(node.get("fqn") or "")
    simple = str(node.get("name") or "Class")
    pkg = str(node.get("package") or "com.acme.lims")
    tier = str(node.get("gxpTier") or "LOW")

    methods = []
    for mid in kg.children(cid):
        md = kg.node(mid) or {}
        if str(md.get("returnType")) == "<init>":
            continue
        if "private" in (md.get("modifiers") or []):
            continue
        name = str(md.get("name"))
        if name.startswith(("get", "set", "is", "toString", "hashCode", "equals")):
            continue
        methods.append(md | {"node_id": mid})
    # Prioritise what actually runs: a test for a method nobody calls proves nothing.
    methods.sort(key=lambda m: (-(int(m.get("runtimeHits") or 0)),
                                -(int(m.get("complexity") or 0))))
    methods = methods[:max_methods]
    if not methods:
        return None

    writes_regulated = any(
        (kg.node(t) or {}).get("regulated")
        for m in kg.children(cid) for t in kg.out_neighbors(m, "WRITES")
    )

    lines: list[str] = [
        f"package {pkg};",
        "",
        "import static org.junit.jupiter.api.Assertions.*;",
        "",
        "import java.math.BigDecimal;",
        "import java.sql.Timestamp;",
        "import java.util.Date;",
        "import java.util.List;",
        "",
        "import org.junit.jupiter.api.BeforeEach;",
        "import org.junit.jupiter.api.DisplayName;",
        "import org.junit.jupiter.api.Test;",
        "",
        "/**",
        f" * CHARACTERISATION TESTS for {fqn}",
        " *",
        " * Generated by ModernRx from the architecture twin.",
        " *",
        " * These tests record the CURRENT behaviour of this component so that the",
        " * modernized implementation can be shown to behave identically. They are",
        " * not correctness tests: where the legacy behaviour is surprising, the",
        " * test encodes the surprising behaviour on purpose.",
        " *",
        f" * GxP tier: {tier}"
        + (f"   Tags: {', '.join(node.get('gxpTags') or [])}" if node.get("gxpTags") else ""),
        f" * Runtime evidence: {int(node.get('runtimeHits') or 0):,} observed calls.",
        " *",
        " * TO COMPLETE: replace each EXPECTED_* placeholder with the value captured",
        " * from the legacy system, then run this suite against legacy and",
        " * modernized builds and require identical results.",
        " */",
        f"@DisplayName(\"Characterisation: {simple}\")",
        f"class {simple}CharacterisationTest {{",
        "",
        f"    private {simple} subject;",
        "",
        "    @BeforeEach",
        "    void setUp() {",
        f"        // TODO wire the real collaborators or a test double for {simple}.",
        f"        // this.subject = new {simple}(...);",
        "    }",
    ]

    for md in methods:
        mname = str(md.get("name"))
        params = md.get("params") or []
        arg_list = ", ".join(
            _sample_value(str(p).rsplit(" ", 1)[0], i) for i, p in enumerate(params)
        )
        ret = str(md.get("returnType") or "void")
        hits = int(md.get("runtimeHits") or 0)
        m_tier = str(md.get("gxpTier") or "LOW")
        writes = [str((kg.node(t) or {}).get("name"))
                  for t in kg.out_neighbors(md["node_id"], "WRITES")]

        lines += [
            "",
            "    @Test",
            f'    @DisplayName("{mname} preserves its current behaviour'
            + (f' ({hits:,} observed calls)' if hits else "") + '")',
            f"    void characterise_{_java_ident(mname)}() {{",
        ]
        if m_tier == "HIGH":
            lines.append(f"        // GxP {m_tier}: this is a critical function. Scripted")
            lines.append("        // testing with independent review is required (CSA).")
        if writes:
            lines.append(f"        // Writes: {', '.join(sorted(set(writes)))}. Assert the stored")
            lines.append("        // record, not only the return value.")
        if md.get("usesNewDate"):
            lines.append("        // Reads the application-server clock: freeze or inject time,")
            lines.append("        // or this test will be flaky and prove nothing.")

        lines.append("")
        if ret in ("void", "<init>"):
            lines += [
                f"        assertDoesNotThrow(() -> subject.{mname}({arg_list}));",
                "        // TODO assert the persisted state that this call produced.",
            ]
        elif ret == "boolean":
            lines += [
                "        boolean EXPECTED_RESULT = true; // TODO capture from the legacy system",
                f"        assertEquals(EXPECTED_RESULT, subject.{mname}({arg_list}));",
            ]
        elif ret.startswith(("List", "Collection", "Set")):
            lines += [
                "        int EXPECTED_SIZE = 0; // TODO capture from the legacy system",
                f"        var actual = subject.{mname}({arg_list});",
                "        assertNotNull(actual);",
                "        assertEquals(EXPECTED_SIZE, actual.size());",
            ]
        else:
            lines += [
                f"        // TODO capture the legacy value for this input",
                f"        Object EXPECTED_RESULT = null;",
                f"        var actual = subject.{mname}({arg_list});",
                "        assertEquals(EXPECTED_RESULT, actual);",
            ]
        if writes and any((kg.node(t) or {}).get("regulated")
                          for t in kg.out_neighbors(md["node_id"], "WRITES")):
            lines += [
                "",
                "        // Part 11 11.10(e): a change to a GxP record must produce an",
                "        // attributable audit-trail entry. Assert it exists.",
                "        // assertAuditEntryWritten(\"<entity>\", \"<key>\", \"<actor>\");",
            ]
        lines.append("    }")

    lines += ["}", ""]

    return GeneratedTest(
        name=f"{simple}CharacterisationTest",
        target=fqn, node_id=cid, kind="unit", tier=tier, language="Java",
        source="\n".join(lines),
        runtime_hits=int(node.get("runtimeHits") or 0),
        rationale=(
            f"{simple} is GxP {tier}"
            + (" and writes regulated records" if writes_regulated else "")
            + f"; {int(node.get('runtimeHits') or 0):,} observed calls make its current "
              f"behaviour the baseline the migration must preserve."
        ),
    )


def generate_http_suite(kg: KnowledgeGraph, cluster_ids: list[str]) -> GeneratedTest | None:
    """One ``.http`` suite exercising the endpoints the traces show in use."""
    rows: list[tuple[str, str, str, int]] = []
    for cid in cluster_ids:
        for member in kg.in_neighbors(cid, "IN_CLUSTER"):
            hits = int((kg.node(member) or {}).get("runtimeHits") or 0)
            tier = str((kg.node(member) or {}).get("gxpTier") or "LOW")
            for e in kg.out_neighbors(member, "EXPOSES"):
                ed = kg.node(e) or {}
                rows.append((str(ed.get("httpMethod")), str(ed.get("path")), tier, hits))
    if not rows:
        return None
    rows.sort(key=lambda r: -r[3])

    lines = [
        "###############################################################",
        "# ModernRx characterisation suite - HTTP level",
        "#",
        "# Run against the LEGACY system first and save every response as the",
        "# baseline. Then run against the MODERNIZED system and diff. Any",
        "# difference is a finding to resolve or to justify and have QA accept.",
        "#",
        "# Ordered by observed call volume, so the busiest paths are covered first.",
        "###############################################################",
        "",
        "@baseUrl = http://localhost:8080",
        "@user = demo.analyst",
        "",
    ]
    for verb, path, tier, hits in rows[:40]:
        v = "GET" if verb == "ANY" else verb
        lines += [
            f"### {v} {path}   [GxP {tier}, {hits:,} observed calls]",
        ]
        if tier == "HIGH":
            lines.append("# CRITICAL FUNCTION: scripted testing and independent review required.")
        lines.append(f"{v} {{{{baseUrl}}}}{path}")
        lines.append("X-Acting-User: {{user}}")
        if v in ("POST", "PUT", "PATCH"):
            lines += ["Content-Type: application/x-www-form-urlencoded", "", "# TODO request body"]
        lines.append("")
    return GeneratedTest(
        name="characterisation-suite.http",
        target="HTTP endpoints", node_id="", kind="http", tier="MIXED",
        language="HTTP", source="\n".join(lines),
        rationale=(
            f"{len(rows)} endpoint(s) exposed by the clusters in this wave. An "
            f"HTTP-level baseline is what makes differential testing possible "
            f"without reading either implementation."
        ),
    )


def generate_data_checks(kg: KnowledgeGraph, cluster_ids: list[str]) -> GeneratedTest | None:
    """SQL reconciliation script for the regulated tables in scope."""
    tables: dict[str, bool] = {}
    for cid in cluster_ids:
        for member in kg.in_neighbors(cid, "IN_CLUSTER"):
            for m in [member, *kg.children(member)]:
                for rel in ("READS", "WRITES"):
                    for t in kg.out_neighbors(m, rel):
                        td = kg.node(t) or {}
                        name = str(td.get("name"))
                        tables[name] = tables.get(name, False) or bool(td.get("regulated"))
    if not tables:
        return None

    lines = [
        "-- ModernRx data-migration reconciliation",
        "--",
        "-- Run on SOURCE and TARGET and compare the output. Every row must match.",
        "-- Record the output as system-generated evidence; a reported count is not evidence.",
        "",
    ]
    for name, regulated in sorted(tables.items(), key=lambda kv: (not kv[1], kv[0])):
        cols = sorted(
            str((kg.node(c) or {}).get("name"))
            for c in kg.out_neighbors(f"table:{name}", "CONTAINS")
        )
        lines += [
            f"-- {'=' * 60}",
            f"-- {name}" + ("   [REGULATED]" if regulated else ""),
            f"-- {'=' * 60}",
            f"SELECT '{name}' AS table_name, COUNT(*) AS row_count FROM {name};",
            "",
        ]
        if cols:
            concat = " || '|' || ".join(f"COALESCE(CAST({c} AS VARCHAR), '~')" for c in cols[:12])
            lines += [
                f"-- Content checksum over {min(len(cols), 12)} column(s), order-independent",
                f"SELECT '{name}' AS table_name,",
                f"       COUNT(*) AS row_count,",
                f"       SUM(HASH('SHA256', {concat})) AS content_checksum",
                f"FROM {name};",
                "",
            ]
        if regulated and ("AUDIT" in name.upper() or "TRAIL" in name.upper()):
            lines += [
                "-- Audit-trail continuity: no gap across the cutover boundary",
                f"SELECT COUNT(*) AS gaps FROM (",
                f"  SELECT AUDIT_ID, LAG(AUDIT_ID) OVER (ORDER BY AUDIT_ID) AS prev",
                f"  FROM {name}",
                f") t WHERE prev IS NOT NULL AND AUDIT_ID <> prev + 1;",
                "",
                "-- Every audit entry still resolves to a subject record",
                f"SELECT ENTITY_NAME, COUNT(*) AS orphaned",
                f"FROM {name} a WHERE NOT EXISTS (",
                "  SELECT 1 FROM SAMPLE s WHERE CAST(s.SAMPLE_ID AS VARCHAR) = a.ENTITY_KEY",
                ") AND a.ENTITY_NAME = 'SAMPLE' GROUP BY ENTITY_NAME;",
                "",
            ]
    return GeneratedTest(
        name="data-reconciliation.sql",
        target=f"{len(tables)} table(s)", node_id="", kind="data", tier="MIXED",
        language="SQL", source="\n".join(lines),
        rationale=(
            f"{sum(1 for v in tables.values() if v)} of {len(tables)} table(s) in "
            f"scope hold regulated records. Row counts and content checksums are "
            f"the minimum evidence that a migration preserved them."
        ),
    )


def generate(
    kg: KnowledgeGraph, cluster_ids: list[str], *, max_classes: int = 10
) -> TestSuite:
    suite = TestSuite()
    members: list[str] = []
    for cid in cluster_ids:
        members.extend(kg.in_neighbors(cid, "IN_CLUSTER"))

    # HIGH tier first, then by observed traffic: generate where it matters.
    rank = {"HIGH": 0, "MEDIUM": 1, "LOW": 2}
    members.sort(key=lambda m: (
        rank.get(str((kg.node(m) or {}).get("gxpTier")), 3),
        -(int((kg.node(m) or {}).get("runtimeHits") or 0)),
    ))

    for cid in members[:max_classes]:
        t = generate_for_class(kg, cid)
        if t is not None:
            suite.tests.append(t)

    http = generate_http_suite(kg, cluster_ids)
    if http:
        suite.tests.append(http)
    data = generate_data_checks(kg, cluster_ids)
    if data:
        suite.tests.append(data)

    covered = {t.node_id for t in suite.tests if t.node_id}
    high = [m for m in members if str((kg.node(m) or {}).get("gxpTier")) == "HIGH"]
    suite.stats = {
        "classes_in_scope": len(members),
        "classes_covered": len(covered),
        "high_tier_in_scope": len(high),
        "high_tier_covered": len([m for m in high if m in covered]),
        "by_kind": {k: sum(1 for t in suite.tests if t.kind == k)
                    for k in ("unit", "http", "data")},
    }
    suite.coverage_note = (
        f"{len(covered)} of {len(members)} class(es) have a generated characterisation "
        f"test, including {suite.stats['high_tier_covered']} of "
        f"{len(high)} HIGH-tier class(es). These are skeletons with the expected "
        f"values left as placeholders: the values must be captured from the legacy "
        f"system, because only the legacy system knows what the current behaviour is. "
        f"Method selection is driven by observed runtime calls, so the busiest and "
        f"most critical paths are covered first."
    )
    return suite
