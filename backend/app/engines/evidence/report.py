def _env() -> Environment:
    env = Environment(
        loader=FileSystemLoader(str(TEMPLATE_DIR)),
        autoescape=select_autoescape(["html", "xml"]),
        trim_blocks=True,
        lstrip_blocks=True,
    )
    env.filters["commify"] = lambda v: f"{int(v):,}" if isinstance(v, (int, float)) else v
    return env


def render_html(data: dict[str, Any]) -> str:
    return _env().get_template("pack.html.j2").render(**data)


def render_pdf(data: dict[str, Any], html: str, out: Path) -> str:
    """Write the PDF. Returns which renderer was used."""
    try:
        from weasyprint import HTML  # optional: better fidelity when present

        HTML(string=html).write_pdf(str(out))
        return "weasyprint"
    except Exception as exc:
        log.info("weasyprint_unavailable", detail=str(exc)[:160])

    _reportlab_pdf(data, out)
    return "reportlab"


def _reportlab_pdf(d: dict[str, Any], out: Path) -> None:
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import (
        KeepTogether,
        PageBreak,
        Paragraph,
        SimpleDocTemplate,
        Spacer,
        Table,
        TableStyle,
    )

    INK = colors.HexColor("#0f172a")
    MUTED = colors.HexColor("#4b5563")
    RULE = colors.HexColor("#d4d8e0")
    BAND = colors.HexColor("#f1f4f9")
    HIGH = colors.HexColor("#b91c1c")
    MED = colors.HexColor("#b45309")
    LOW = colors.HexColor("#15803d")
    ACCENT = colors.HexColor("#1d4ed8")

    ss = getSampleStyleSheet()
    body = ParagraphStyle("body", parent=ss["BodyText"], fontName="Helvetica",
                          fontSize=8.6, leading=12.4, textColor=INK,
                          alignment=TA_LEFT, spaceAfter=5)
    small = ParagraphStyle("small", parent=body, fontSize=7.5, leading=10.4, textColor=MUTED)
    cell = ParagraphStyle("cell", parent=body, fontSize=7.4, leading=9.8, spaceAfter=0)
    cellb = ParagraphStyle("cellb", parent=cell, fontName="Helvetica-Bold")
    h1 = ParagraphStyle("h1", parent=ss["Heading1"], fontName="Helvetica-Bold",
                        fontSize=16, leading=19, textColor=INK, spaceBefore=4, spaceAfter=7)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], fontName="Helvetica-Bold",
                        fontSize=11.5, leading=14, textColor=INK, spaceBefore=13, spaceAfter=5)
    h3 = ParagraphStyle("h3", parent=ss["Heading3"], fontName="Helvetica-Bold",
                        fontSize=9.4, leading=12, textColor=ACCENT, spaceBefore=9, spaceAfter=3)

    def esc(v: Any) -> str:
        return (str(v if v is not None else "")
                .replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))

    def p(text: Any, style=body) -> Paragraph:
        return Paragraph(esc(text), style)

    def tier_colour(tier: str):
        return {"HIGH": HIGH, "MEDIUM": MED}.get(str(tier).upper(), LOW)

    def table(rows: list[list[Any]], widths: list[float], *, header: bool = True,
              tier_col: int | None = None) -> Table:
        t = Table(rows, colWidths=widths, repeatRows=1 if header else 0, hAlign="LEFT")
        style = [
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LINEBELOW", (0, 0), (-1, -2), 0.3, RULE),
            ("TOPPADDING", (0, 0), (-1, -1), 3.5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3.5),
            ("LEFTPADDING", (0, 0), (-1, -1), 5),
            ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ]
        if header:
            style += [
                ("BACKGROUND", (0, 0), (-1, 0), BAND),
                ("LINEBELOW", (0, 0), (-1, 0), 0.7, INK),
            ]
        if tier_col is not None:
            for i, row in enumerate(rows[1 if header else 0:], start=1 if header else 0):
                style.append(("TEXTCOLOR", (tier_col, i), (tier_col, i),
                              tier_colour(str(row[tier_col]))))
        t.setStyle(TableStyle(style))
        return t

    def bullets(items: list[Any], style=body, limit: int = 40) -> list[Any]:
        return [Paragraph(f"&bull;&nbsp; {esc(i)}", style) for i in (items or [])[:limit]]

    story: list[Any] = []
    W = A4[0] - 32 * mm       # usable width

    # ---------------------------------------------------------------- cover
    proj = d.get("project") or {}
    wave_meta = d.get("wave_meta") or {}
    story += [
        p("EVIDENCE PACK", ParagraphStyle("kicker", parent=small, fontSize=8,
                                          textColor=ACCENT, spaceAfter=2)),
        p(f"{proj.get('name', 'System')} - Wave {d.get('wave')}", h1),
        p(wave_meta.get("title") or "Migration wave", ParagraphStyle(
            "sub", parent=body, fontSize=10, textColor=MUTED, spaceAfter=10)),
    ]
    story.append(table([
        [p("Generated", cellb), p(d.get("generated_at"), cell),
         p("Target cloud", cellb), p(d.get("target_cloud"), cell)],
        [p("Wave window", cellb),
         p(f"{wave_meta.get('start_date', '-')} to {wave_meta.get('end_date', '-')}", cell),
         p("Tasks in wave", cellb), p(wave_meta.get("task_count", "-"), cell)],
        [p("Components", cellb), p((d.get("system") or {}).get("components"), cell),
         p("Regulated tables", cellb),
         p(len((d.get("system") or {}).get("regulated_tables") or []), cell)],
        [p("Generated by", cellb), p("ModernRx", cell),
         p("Status", cellb), p("DRAFT - requires QA review", cellb)],
    ], [W * 0.17, W * 0.33, W * 0.17, W * 0.33], header=False))

    story += [Spacer(1, 9)]
    warn = Table([[p(d.get("disclaimer"), small)]], colWidths=[W], hAlign="LEFT")
    warn.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#fff7ed")),
        ("BOX", (0, 0), (-1, -1), 0.7, colors.HexColor("#f59e0b")),
        ("LEFTPADDING", (0, 0), (-1, -1), 8), ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 7), ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
    ]))
    story += [warn, Spacer(1, 10)]

    story += [p("Contents", h3)]
    story.append(table(
        [[p(k, cellb), p(v, cell)] for k, v in (d.get("sections") or {}).items()],
        [W * 0.06, W * 0.94], header=False,
    ))

    # ------------------------------------------------- 1. system description
    story += [PageBreak(), p("1. System description", h2)]
    sysd = d.get("system") or {}
    story.append(table([
        [p("Property", cellb), p("Value", cellb)],
        [p("Lines of code", cell), p(f"{int(sysd.get('loc') or 0):,}", cell)],
        [p("Primary language", cell), p(sysd.get("primary_language"), cell)],
        [p("Components analysed", cell), p(sysd.get("components"), cell)],
        [p("Database tables", cell),
         p(f"{sysd.get('tables')} ({len(sysd.get('regulated_tables') or [])} regulated)", cell)],
        [p("HTTP endpoints", cell), p(sysd.get("endpoints"), cell)],
        [p("Knowledge-graph size", cell),
         p(f"{(sysd.get('graph') or {}).get('nodes')} nodes, "
           f"{(sysd.get('graph') or {}).get('edges')} relationships", cell)],
        [p("Runtime use cases observed", cell), p(len(sysd.get("use_cases") or []), cell)],
    ], [W * 0.3, W * 0.7]))

    if sysd.get("regulated_tables"):
        story += [p("Regulated tables", h3),
                  p(", ".join(sysd["regulated_tables"]), small)]
    if sysd.get("use_cases"):
        story += [p("Business use cases captured from runtime traces", h3),
                  *bullets(sysd["use_cases"], small, 20)]
    if sysd.get("eol_libraries"):
        story += [p("End-of-life dependencies", h3)]
        story.append(table(
            [[p("Library", cellb), p("Version", cellb), p("Why it matters", cellb)]]
            + [[p(l.get("name"), cell), p(l.get("version"), cell), p(l.get("reason"), cell)]
               for l in sysd["eol_libraries"][:14]],
            [W * 0.26, W * 0.15, W * 0.59],
        ))

    # ------------------------------------------- 2. intended use & GxP impact
    story += [PageBreak(), p("2. Intended use and GxP impact", h2)]
    assurance = d.get("assurance") or {}
    story += [p(assurance.get("summary", ""), body)]

    comps = (assurance.get("components") or [])
    if comps:
        story += [p("Intended use per component", h3)]
        story.append(table(
            [[p("Component", cellb), p("Tier", cellb), p("Intended use", cellb)]]
            + [[p(str(c.get("name", "")).rsplit(".", 1)[-1], cell),
                p(c.get("tier"), cellb),
                p(c.get("intended_use"), cell)]
               for c in comps[:26]],
            [W * 0.2, W * 0.09, W * 0.71], tier_col=1,
        ))

    gaps = (d.get("gxp") or {}).get("gaps") or []
    if gaps:
        story += [p("Compliance gaps identified in the current system", h3)]
        for g in gaps[:10]:
            block = [
                p(f"[{g.get('severity')}] {g.get('title')}", cellb),
                p(f"Reference: {g.get('clause')}", small),
                p(g.get("detail"), cell),
                p(f"Remediation: {g.get('remediation')}", cell),
            ]
            if g.get("evidence_names"):
                block.append(p("Evidence: " + ", ".join(
                    str(n).rsplit(".", 1)[-1] for n in g["evidence_names"][:6]), small))
            t = Table([[block]], colWidths=[W], hAlign="LEFT")
            t.setStyle(TableStyle([
                ("LINEBEFORE", (0, 0), (0, -1), 2.2, tier_colour(
                    "HIGH" if g.get("severity") == "HIGH" else
                    "MEDIUM" if g.get("severity") == "MEDIUM" else "LOW")),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
            ]))
            story += [KeepTogether([t]), Spacer(1, 3)]

    # ------------------------------------------- 3. risk-based assurance plan
    story += [PageBreak(), p("3. Risk-based assurance plan (CSA)", h2)]
    tc = assurance.get("tier_counts") or {}
    story += [p(
        f"Computer Software Assurance scales the assurance effort to risk. Of the "
        f"{sum(tc.values())} component(s) in this wave, {tc.get('HIGH', 0)} require "
        f"scripted testing with independent review, {tc.get('MEDIUM', 0)} are covered "
        f"by unscripted testing with recorded results, and {tc.get('LOW', 0)} by "
        f"automated and vendor evidence.", body)]

    for tier in ("HIGH", "MEDIUM", "LOW"):
        spec = (assurance.get("approach_by_tier") or {}).get(tier)
        if not spec or not tc.get(tier):
            continue
        story += [p(f"{tier} tier - {spec['approach']} ({tc.get(tier, 0)} component(s))", h3),
                  p(spec["rationale"], small),
                  p("Activities:", cellb), *bullets(spec["activities"], cell),
                  p("Evidence to retain:", cellb), *bullets(spec["evidence"], cell),
                  p(f"Reviewer: {spec['reviewer']}   |   Approval: {spec['approval']}", small)]

    crit = [c for c in comps if c.get("critical_functions")]
    if crit:
        story += [p("Critical functions requiring scripted test cases", h3)]
        rows = [[p("Component", cellb), p("Critical function and acceptance criterion", cellb)]]
        for c in crit[:16]:
            rows.append([
                p(str(c.get("name", "")).rsplit(".", 1)[-1], cell),
                p("; ".join(c["critical_functions"][:4]), cell),
            ])
        story.append(table(rows, [W * 0.22, W * 0.78]))

    # ----------------------------------------------- 4. characterisation tests
    story += [PageBreak(), p("4. Characterisation tests", h2)]
    tests = d.get("tests") or {}
    story += [p(tests.get("coverage_note", ""), body)]
    if tests.get("tests"):
        story.append(table(
            [[p("Artefact", cellb), p("Kind", cellb), p("Tier", cellb), p("Why", cellb)]]
            + [[p(t.get("name"), cell), p(t.get("kind"), cell), p(t.get("tier"), cellb),
                p(t.get("rationale"), cell)]
               for t in tests["tests"][:16]],
            [W * 0.24, W * 0.09, W * 0.09, W * 0.58], tier_col=2,
        ))

    # ------------------------------------------------- 5. differential testing
    story += [PageBreak(), p("5. Shadow / differential testing plan", h2)]
    diff = d.get("differential") or {}
    story += [p(diff.get("method", ""), body),
              p(f"Duration: {diff.get('duration', '')}", small),
              p("Comparison rules", h3), *bullets(diff.get("comparison_rules"), cell),
              p("Exit criteria", h3), *bullets(diff.get("exit_criteria"), cell)]
    if diff.get("endpoints"):
        story += [p("Endpoints in scope", h3)]
        story.append(table(
            [[p("Endpoint", cellb), p("Tier", cellb), p("Handler", cellb)]]
            + [[p(e.get("endpoint"), cell), p(e.get("gxp_tier"), cellb),
                p(str(e.get("handler", "")).rsplit(".", 2)[-1], cell)]
               for e in diff["endpoints"][:20]],
            [W * 0.4, W * 0.1, W * 0.5], tier_col=1,
        ))

    # ---------------------------------------------------- 6. data migration
    story += [PageBreak(), p("6. Data migration checks", h2)]
    dm = d.get("data_migration") or {}
    story += [p(f"{dm.get('regulated_count', 0)} of {len(dm.get('tables') or [])} table(s) "
                f"in scope hold regulated records.", body),
              *bullets(dm.get("general_requirements"), cell)]
    if dm.get("tables"):
        story += [p("Per-table verification", h3)]
        story.append(table(
            [[p("Table", cellb), p("Reg.", cellb), p("Mode", cellb), p("Checks", cellb)]]
            + [[p(t.get("table"), cell), p("YES" if t.get("regulated") else "-",
                                           cellb if t.get("regulated") else cell),
                p(t.get("modes"), cell), p("; ".join(t.get("checks") or []), cell)]
               for t in dm["tables"][:18]],
            [W * 0.17, W * 0.07, W * 0.07, W * 0.69],
        ))

    # ------------------------------------------------------ 7. traceability
    story += [PageBreak(), p("7. Traceability matrix", h2)]
    tr = d.get("traceability") or []
    story += [p(f"{len(tr)} requirement-to-evidence link(s), derived from the GxP "
                f"criticality analysis.", body)]
    if tr:
        story.append(table(
            [[p("ID", cellb), p("Requirement", cellb), p("Component", cellb),
              p("Tier", cellb), p("Test approach", cellb)]]
            + [[p(r.get("id"), cell), p(r.get("requirement"), cell),
                p(str(r.get("component", "")).rsplit(".", 1)[-1], cell),
                p(r.get("gxp_tier"), cellb), p(r.get("test_approach"), cell)]
               for r in tr[:34]],
            [W * 0.11, W * 0.34, W * 0.15, W * 0.08, W * 0.32], tier_col=3,
        ))

    # --------------------------------------------------------- 8. rollback
    story += [PageBreak(), p("8. Rollback plan", h2)]
    rb = d.get("rollback") or {}
    story += [p("Trigger criteria", h3), *bullets(rb.get("trigger_criteria"), cell),
              p("Procedure", h3), *bullets(rb.get("procedure"), cell),
              p("Regulated data created after cutover", h3),
              p(rb.get("data_considerations"), body),
              p(f"Rollback window: {rb.get('rollback_window', '')}", small),
              p(f"Decision authority: {rb.get('decision_authority', '')}", small)]

    # ------------------------------------------------ 9. supplier oversight
    story += [PageBreak(), p("9. Cloud supplier oversight checklist", h2)]
    sup = d.get("supplier") or {}
    story += [p(sup.get("basis", ""), small)]
    story.append(table(
        [[p("Item", cellb), p("What is required", cellb), p("Owner", cellb), p("When", cellb)]]
        + [[p(i.get("item"), cell), p(i.get("detail"), cell),
            p(i.get("owner"), cell), p(i.get("status"), cell)]
           for i in (sup.get("items") or [])],
        [W * 0.22, W * 0.48, W * 0.14, W * 0.16],
    ))

    # ------------------------------------------------------- decisions + sign-off
    story += [PageBreak(), p("Annex A - Modernization decisions in this wave", h2)]
    decs = d.get("decisions") or []
    if decs:
        story.append(table(
            [[p("Cluster", cellb), p("Strategy", cellb), p("Conf.", cellb),
              p("Effort (wks)", cellb), p("Rationale", cellb)]]
            + [[p(str(x.get("cluster_id")), cell), p(x.get("strategy"), cellb),
                p(f"{float(x.get('confidence') or 0):.0%}", cell),
                p("/".join(str(v) for v in (x.get("effort_weeks") or [])), cell),
                p(x.get("rationale"), cell)]
               for x in decs[:14]],
            [W * 0.13, W * 0.12, W * 0.07, W * 0.13, W * 0.55],
        ))
        for x in decs:
            if x.get("dissent"):
                story += [p(f"Recorded dissent - {x.get('cluster_id')}", h3)]
                story.append(table(
                    [[p("Agent", cellb), p("Position", cellb), p("Reason", cellb)]]
                    + [[p(v.get("agent"), cell), p(v.get("position"), cell),
                        p(v.get("reason"), cell)] for v in x["dissent"][:5]],
                    [W * 0.2, W * 0.13, W * 0.67],
                ))

    story += [p("Annex B - Review and approval", h2),
              p("This pack is a draft. Signing below records that the named "
                "reviewer has assessed its content for this wave.", small),
              Spacer(1, 6)]
    story.append(table([
        [p("Role", cellb), p("Name", cellb), p("Signature", cellb), p("Date", cellb)],
        [p("Prepared by (ModernRx)", cell), p("Automated draft", cell), p("n/a", cell),
         p(str(d.get("generated_at", ""))[:10], cell)],
        [p("Reviewed by (System owner)", cell), p(" ", cell), p(" ", cell), p(" ", cell)],
        [p("Approved by (QA)", cell), p(" ", cell), p(" ", cell), p(" ", cell)],
        [p("Noted by (Qualified Person)", cell), p(" ", cell), p(" ", cell), p(" ", cell)],
    ], [W * 0.3, W * 0.26, W * 0.26, W * 0.18]))

    if d.get("approvals"):
        story += [p("Decisions already approved in ModernRx", h3)]
        story.append(table(
            [[p("Decision", cellb), p("Approver", cellb), p("When", cellb), p("Comment", cellb)]]
            + [[p(a.get("decision_id"), cell), p(a.get("user"), cell),
                p(str(a.get("ts", ""))[:19], cell), p(a.get("comment"), cell)]
               for a in d["approvals"][:16]],
            [W * 0.18, W * 0.2, W * 0.22, W * 0.4],
        ))

    # --------------------------------------------------------------- render
    def decorate(canvas, doc_) -> None:
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(MUTED)
        canvas.drawString(16 * mm, 10 * mm,
                          f"{proj.get('name', '')} - Evidence Pack, Wave {d.get('wave')} - DRAFT")
        canvas.drawRightString(A4[0] - 16 * mm, 10 * mm, f"Page {doc_.page}")
        canvas.setStrokeColor(RULE)
        canvas.setLineWidth(0.3)
        canvas.line(16 * mm, 13 * mm, A4[0] - 16 * mm, 13 * mm)
        canvas.restoreState()

    doc = SimpleDocTemplate(
        str(out), pagesize=A4,
        leftMargin=16 * mm, rightMargin=16 * mm, topMargin=15 * mm, bottomMargin=18 * mm,
        title=f"{proj.get('name', 'System')} - Evidence Pack Wave {d.get('wave')}",
        author="ModernRx", subject="GxP-aware modernization evidence pack",
    )
    doc.build(story, onFirstPage=decorate, onLaterPages=decorate)


def generate_pack(
    kg: KnowledgeGraph,
    *,
    project: dict[str, Any],
    wave: int,
    schedule: dict[str, Any],
    decisions: list[dict[str, Any]],
    out_dir: Path | None = None,
    **extra: Any,
) -> EvidencePack:
    data = build_pack_data(
        kg, project=project, wave=wave, schedule=schedule, decisions=decisions, **extra
    )
    out_dir = out_dir or settings.packs_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    stem = f"{project.get('id', 'project')}-wave{wave}"

    html = render_html(data)
    html_path = out_dir / f"{stem}.html"
    html_path.write_text(html, encoding="utf-8")

    pdf_path = out_dir / f"{stem}.pdf"
    renderer = render_pdf(data, html, pdf_path)

    log.info("evidence_pack_generated", wave=wave, renderer=renderer,
             pdf_kb=round(pdf_path.stat().st_size / 1024, 1))
    return EvidencePack(
        project_id=str(project.get("id", "")), wave=wave, data=data,
        html_path=html_path, pdf_path=pdf_path, renderer=renderer,
    )
