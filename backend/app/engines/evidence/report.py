"""Engine 7, part 3 — the Evidence Pack document (PRD §14).

Produces both an HTML pack (Jinja2) and a real PDF.

The PRD specifies WeasyPrint. On Windows WeasyPrint needs a GTK/Pango runtime
installed outside pip, which is a hard dependency for a tool whose pitch is that
it runs on your own machine. ReportLab is pure Python, renders on every
platform, and gives precise control over the tables this document is mostly made
of. WeasyPrint is still used when it happens to be importable, because its HTML
fidelity is better - so the better output is taken when available and the pack is
never unavailable.

Sections follow §14 exactly: system description, intended use and GxP impact,
risk-based assurance plan, characterisation tests, differential testing plan,
data-migration checks, traceability matrix, rollback plan, supplier oversight.
"""
from __future__ import annotations

import datetime as dt
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from jinja2 import Environment, FileSystemLoader, select_autoescape

from ...config import settings
from ...core.logging import get_logger
from ...db.graph import KnowledgeGraph
from ..twin import c4
from . import csa_plan, testgen

log = get_logger("evidence")

TEMPLATE_DIR = Path(__file__).parent / "templates"

DISCLAIMER = (
    "Draft generated by ModernRx to support - not replace - the organization's "
    "validation process. Every section requires review and approval by qualified "
    "personnel before use. ModernRx is a decision-support tool: it does not "
    "validate software, and its output is not evidence of validation."
)


@dataclass
class EvidencePack:
    project_id: str
    wave: int
    data: dict[str, Any] = field(default_factory=dict)
    html_path: Path | None = None
    pdf_path: Path | None = None
    renderer: str = ""

    def as_dict(self) -> dict[str, Any]:
        return {
            "project_id": self.project_id, "wave": self.wave,
            "html_path": str(self.html_path) if self.html_path else None,
            "pdf_path": str(self.pdf_path) if self.pdf_path else None,
            "renderer": self.renderer,
            "sections": list(self.data.get("sections", {})),
            "generated_at": self.data.get("generated_at"),
        }


def build_pack_data(
    kg: KnowledgeGraph,
    *,
    project: dict[str, Any],
    wave: int,
    schedule: dict[str, Any],
    decisions: list[dict[str, Any]],
    gxp_summary: dict[str, Any] | None = None,
    readiness_summary: dict[str, Any] | None = None,
    decomposition: dict[str, Any] | None = None,
    montecarlo: dict[str, Any] | None = None,
    approvals: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    """Assemble every section of the pack for one wave."""
    by_cluster = {str(d.get("cluster_id")): d for d in decisions}
    wave_tasks = [t for t in (schedule.get("tasks") or []) if int(t.get("wave", -1)) == wave]
    cluster_ids = [str(t["cluster_id"]) for t in wave_tasks
                   if t.get("cluster_id") and kg.has(str(t["cluster_id"]))]

    diagrams = c4.generate_all(kg)
    suite = testgen.generate(kg, cluster_ids)

    wave_meta = next((w for w in (schedule.get("waves") or []) if int(w["wave"]) == wave), {})
    target_cloud = str(project.get("target_cloud") or "AWS")

    approved = [a for a in (approvals or []) if a.get("action") == "approve"]

    return {
        "generated_at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "disclaimer": DISCLAIMER,
        "project": project,
        "wave": wave,
        "wave_meta": wave_meta,
        "target_cloud": target_cloud,
        "sections": {
            "1": "System description",
            "2": "Intended use and GxP impact",
            "3": "Risk-based assurance plan (CSA)",
            "4": "Characterisation tests",
            "5": "Shadow / differential testing plan",
            "6": "Data migration checks",
            "7": "Traceability matrix",
            "8": "Rollback plan",
            "9": "Cloud supplier oversight checklist",
        },

        # 1. System description
        "system": {
            "name": project.get("name"),
            "loc": (kg.nodes("Project") or [{}])[0].get("loc"),
            "primary_language": (kg.nodes("Project") or [{}])[0].get("primaryLanguage"),
            "languages": (kg.nodes("Project") or [{}])[0].get("languages") or {},
            "graph": kg.stats(),
            "diagrams": diagrams,
            "components": len(kg.classes()),
            "tables": len(kg.nodes("Table")),
            "regulated_tables": sorted(
                str(t.get("name")) for t in kg.nodes("Table") if t.get("regulated")
            ),
            "endpoints": len(kg.nodes("Endpoint")),
            "use_cases": sorted(str(u.get("name")) for u in kg.nodes("UseCase")),
            "eol_libraries": [
                {"name": l.get("name"), "version": l.get("version"), "reason": l.get("eolReason")}
                for l in kg.nodes("Library") if l.get("eol")
            ],
        },

        # 2. Intended use and GxP impact
        "gxp": {
            "summary": gxp_summary or {},
            "gaps": [
                {**g, "evidence_names": [
                    str((kg.node(n) or {}).get("fqn") or (kg.node(n) or {}).get("name") or n)
                    for n in (g.get("evidence_node_ids") or [])[:8]
                ]}
                for g in ((gxp_summary or {}).get("gaps") or [])
            ],
        },

        # 3. Risk-based assurance plan
        "assurance": csa_plan.build_wave_plan(kg, wave, wave_tasks, by_cluster),

        # 4. Characterisation tests
        "tests": suite.as_dict(),

        # 5. Differential testing
        "differential": csa_plan.differential_testing_plan(kg, cluster_ids),

        # 6. Data migration
        "data_migration": csa_plan.data_migration_checks(kg, cluster_ids),

        # 7. Traceability
        "traceability": csa_plan.traceability_matrix(kg, cluster_ids, by_cluster),

        # 8. Rollback
        "rollback": csa_plan.rollback_plan(kg, wave, wave_tasks),

        # 9. Supplier oversight
        "supplier": csa_plan.supplier_oversight_checklist(target_cloud),

        # Context the reviewer will want
        "decisions": [by_cluster[c] for c in cluster_ids if c in by_cluster],
        "readiness": readiness_summary or {},
        "decomposition": decomposition or {},
        "montecarlo": montecarlo or {},
        "approvals": approved,
        "schedule": {
            "makespan_weeks": schedule.get("makespan_weeks"),
            "solver": schedule.get("solver"),
            "waves": schedule.get("waves"),
            "freeze_windows": schedule.get("freeze_windows"),
        },
    }


