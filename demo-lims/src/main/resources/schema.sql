-- AcmeLIMS physical schema.
-- PLANTED FINDING: AUDIT_TRAIL has no REASON column, so changes to GxP records
-- cannot carry a reason-for-change as 21 CFR Part 11 §11.10(e) requires.

CREATE TABLE SAMPLE (
  SAMPLE_ID      NUMBER(12)    NOT NULL,
  SAMPLE_CODE    VARCHAR(40)   NOT NULL,
  PRODUCT_CODE   VARCHAR(40),
  BATCH_ID       NUMBER(12),
  MATRIX         VARCHAR(60),
  RECEIVED_AT    TIMESTAMP,
  RECEIVED_BY    VARCHAR(60),
  STATUS         VARCHAR(20),
  CUSTODY_NOTE   VARCHAR(400)
);

CREATE TABLE CHAIN_OF_CUSTODY (
  COC_ID         NUMBER(12)    NOT NULL,
  SAMPLE_ID      NUMBER(12)    NOT NULL,
  FROM_LOCATION  VARCHAR(80),
  TO_LOCATION    VARCHAR(80),
  MOVED_AT       TIMESTAMP,
  MOVED_BY       VARCHAR(60)
);

CREATE TABLE TEST_SPECIFICATION (
  SPEC_ID        NUMBER(12)    NOT NULL,
  PRODUCT_CODE   VARCHAR(40)   NOT NULL,
  ANALYTE        VARCHAR(80),
  LOWER_LIMIT    DECIMAL(18,6),
  UPPER_LIMIT    DECIMAL(18,6),
  UNIT           VARCHAR(20),
  EFFECTIVE_FROM DATE,
  VERSION        NUMBER(4)
);

CREATE TABLE RESULT (
  RESULT_ID      NUMBER(12)    NOT NULL,
  SAMPLE_ID      NUMBER(12)    NOT NULL,
  ANALYTE        VARCHAR(80),
  VALUE_NUM      DECIMAL(18,6),
  UNIT           VARCHAR(20),
  SPEC_ID        NUMBER(12),
  OOS_FLAG       VARCHAR(1),
  ENTERED_AT     TIMESTAMP,
  ENTERED_BY     VARCHAR(60),
  REVIEW_STATUS  VARCHAR(20),
  INSTRUMENT_ID  VARCHAR(40)
);

CREATE TABLE RESULT_SIGNATURE (
  SIG_ID             NUMBER(12)  NOT NULL,
  RESULT_ID          NUMBER(12)  NOT NULL,
  SIGNED_BY          VARCHAR(60),
  SIGNED_AT          TIMESTAMP,
  SIGNATURE_MEANING  VARCHAR(80),
  SIGNATURE_HASH     VARCHAR(128)
);

CREATE TABLE BATCH (
  BATCH_ID         NUMBER(12)  NOT NULL,
  BATCH_NUMBER     VARCHAR(40) NOT NULL,
  PRODUCT_CODE     VARCHAR(40),
  MANUFACTURED_AT  DATE,
  DISPOSITION      VARCHAR(20),
  DISPOSITION_BY   VARCHAR(60),
  DISPOSITION_AT   TIMESTAMP,
  QP_NAME          VARCHAR(80)
);

CREATE TABLE DEVIATION (
  DEVIATION_ID   NUMBER(12)  NOT NULL,
  BATCH_ID       NUMBER(12),
  RESULT_ID      NUMBER(12),
  SEVERITY       VARCHAR(20),
  DESCRIPTION    VARCHAR(2000),
  RAISED_AT      TIMESTAMP,
  RAISED_BY      VARCHAR(60),
  STATUS         VARCHAR(20)
);

CREATE TABLE CAPA (
  CAPA_ID        NUMBER(12)  NOT NULL,
  DEVIATION_ID   NUMBER(12),
  ACTION_PLAN    VARCHAR(2000),
  OWNER          VARCHAR(60),
  DUE_DATE       DATE,
  STATUS         VARCHAR(20)
);

CREATE TABLE STABILITY_STUDY (
  STUDY_ID       NUMBER(12)  NOT NULL,
  PRODUCT_CODE   VARCHAR(40),
  TIMEPOINT      VARCHAR(20),
  CONDITION_TEXT VARCHAR(80),
  PULLED_AT      TIMESTAMP,
  SAMPLE_ID      NUMBER(12)
);

CREATE TABLE INSTRUMENT_IMPORT (
  IMPORT_ID      NUMBER(12)  NOT NULL,
  FILE_NAME      VARCHAR(260),
  INSTRUMENT_ID  VARCHAR(40),
  IMPORTED_AT    TIMESTAMP,
  ROW_COUNT      NUMBER(8),
  STATUS         VARCHAR(20)
);

-- PLANTED FINDING: no REASON column; also no OLD_VALUE/NEW_VALUE pairing for
-- deletes, and WHO is a free-text string rather than a user-table reference.
CREATE TABLE AUDIT_TRAIL (
  AUDIT_ID       NUMBER(12)  NOT NULL,
  ENTITY_NAME    VARCHAR(60),
  ENTITY_KEY     VARCHAR(60),
  FIELD_NAME     VARCHAR(60),
  OLD_VALUE      VARCHAR(400),
  NEW_VALUE      VARCHAR(400),
  CHANGED_BY     VARCHAR(60),
  CHANGED_AT     TIMESTAMP,
  ACTION_TYPE    VARCHAR(20)
);

CREATE TABLE LIMS_USER (
  USER_ID        NUMBER(12)  NOT NULL,
  USERNAME       VARCHAR(60) NOT NULL,
  FULL_NAME      VARCHAR(120),
  PASSWORD_HASH  VARCHAR(200),
  ACTIVE_FLAG    VARCHAR(1),
  LAST_LOGIN_AT  TIMESTAMP
);

CREATE TABLE LIMS_ROLE (
  ROLE_ID        NUMBER(12)  NOT NULL,
  ROLE_NAME      VARCHAR(60) NOT NULL,
  DESCRIPTION    VARCHAR(200)
);

CREATE TABLE USER_ROLE (
  USER_ID        NUMBER(12)  NOT NULL,
  ROLE_ID        NUMBER(12)  NOT NULL
);

CREATE TABLE COA_REPORT (
  COA_ID         NUMBER(12)  NOT NULL,
  BATCH_ID       NUMBER(12),
  GENERATED_AT   TIMESTAMP,
  GENERATED_BY   VARCHAR(60),
  FILE_PATH      VARCHAR(400)
);
